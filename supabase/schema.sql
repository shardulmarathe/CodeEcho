-- pgvector ANN index for RAG similarity search.
-- HNSW (not ivfflat): ivfflat with a small corpus + a strict meta.bucket filter probes too
-- few clusters and under-returns (fewer than match_count, sometimes missing the best chunks).
-- HNSW gives high recall out of the box, needs no probe tuning, and scales. Exact-scan is
-- also fine below ~10k rows if you prefer to drop the index entirely.
create index if not exists idx_kb_embedding on kb_documents
  using hnsw (embedding vector_cosine_ops);

-- Top-k cosine match for RAG retrieval (called by kb_store.retrieve_similar via RPC).
create or replace function match_kb_documents(
    query_embedding vector(768),
    match_count int default 4,
    filter_kind text default null,
    filter_bucket text default null
)
returns table (id uuid, kind text, ref text, content text, meta jsonb, similarity float)
language sql stable as $$
    select id, kind, ref, content, meta,
           1 - (embedding <=> query_embedding) as similarity
    from kb_documents
    where embedding is not null
      and (filter_kind is null or kind = filter_kind)
      and (filter_bucket is null or meta->>'bucket' = filter_bucket)
    order by embedding <=> query_embedding
    limit match_count;
$$;

-- Full-text index for the keyword (sparse) half of hybrid retrieval.
create index if not exists idx_kb_content_fts
  on kb_documents using gin (to_tsvector('english', content));

-- HYBRID retrieval: dense pgvector + Postgres full-text, fused with Reciprocal Rank
-- Fusion (RRF). Each retriever contributes 1/(rrf_k + rank); missing side contributes 0.
-- Sparse half degrades to nothing on an empty tsquery, so this reduces to dense-only for
-- keyword-less queries. Called by kb_store.retrieve_similar via RPC.
create or replace function match_kb_documents_hybrid(
    query_embedding vector(768),
    query_text text,
    match_count int default 4,
    filter_kind text default null,
    filter_bucket text default null,
    pool int default 30,
    rrf_k int default 60
)
returns table (id uuid, kind text, ref text, content text, meta jsonb, score float)
language sql stable as $$
    with dense as (
        select d.id,
               row_number() over (order by d.embedding <=> query_embedding) as rnk
        from kb_documents d
        where d.embedding is not null
          and (filter_kind is null or d.kind = filter_kind)
          and (filter_bucket is null or d.meta->>'bucket' = filter_bucket)
        order by d.embedding <=> query_embedding
        limit pool
    ),
    sparse as (
        select d.id,
               row_number() over (
                   order by ts_rank(to_tsvector('english', d.content),
                                    websearch_to_tsquery('english', query_text)) desc
               ) as rnk
        from kb_documents d
        where (filter_kind is null or d.kind = filter_kind)
          and (filter_bucket is null or d.meta->>'bucket' = filter_bucket)
          and to_tsvector('english', d.content) @@ websearch_to_tsquery('english', query_text)
        order by ts_rank(to_tsvector('english', d.content),
                         websearch_to_tsquery('english', query_text)) desc
        limit pool
    ),
    fused as (
        select coalesce(dense.id, sparse.id) as id,
               coalesce(1.0 / (rrf_k + dense.rnk), 0) +
               coalesce(1.0 / (rrf_k + sparse.rnk), 0) as score
        from dense
        full outer join sparse on dense.id = sparse.id
    )
    select d.id, d.kind, d.ref, d.content, d.meta, f.score
    from fused f
    join kb_documents d on d.id = f.id
    order by f.score desc
    limit match_count;
$$;

-- ---------------------------------------------------------------------------
-- New-user profile row. auth.users.id is a uuid; profiles.user_id is text so
-- existing guest-era rows stay valid. The function is security definer so the
-- auth admin can insert into public.profiles.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (user_id)
  values (new.id::text)
  on conflict (user_id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

